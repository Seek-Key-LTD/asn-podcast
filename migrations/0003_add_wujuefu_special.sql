### 【序】

茶者，人在草木间也。拆其字：草头为双十，人木为八十有八，合一百零八之数，故称茶寿。上合天罡三十六，下应地煞七十二。一叶至微，暗合天地之数；是以华夏以茶为精神，炎黄以茶为图腾。

昔人论华夷之辨，约有三端：血缘、地缘、冠服。千禧以降，混血之家日众，跨海而居者日多，洋装而裹中国心者比比皆是。以余观之，华夷之隔，不过一茶耳——**认这片叶子者，皆是故人。**

唐有陆羽著《茶经》，千年之距；东瀛有冈仓天心著《茶书》，烟海之隔。东坡居士尝以一百二十句长诗《寄周安孺茶》，写尽人与茶之缘。己亥端午，客居感怀；适有湖北大学同窗故人携恩施富硒之茗（恩施玉露）赴京农展馆参展，余欲为同窗壮其声势；值岁逢风云激荡，感怀系之，乃不揣浅陋，挑战千文之限，以五绝为体，以茶史为经，一韵到底，双栏对位，成十六章、二百五十六句、凡一千二百八十字，名曰《茶史五绝赋》。东坡百二十句，余不能和，乃倍之——以赠故人，兼以自遣。

夫形而上者谓之道，形而下者谓之器，执其中者谓之政。山不厌高，水不厌深，周公吐哺，天下归心——茶之为物，亦犹是也。

